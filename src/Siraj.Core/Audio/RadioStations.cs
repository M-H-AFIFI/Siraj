namespace Siraj.Core.Audio;

public enum RadioKind { Broadcast, Channel }

public enum RadioFilter { All, Broadcasts, Reciters, TafsirAndSunnah }

public sealed record RadioStation(
    string Id,
    string NameAr, string NameEn, string NameTr, string NameUr,
    string DescAr, string DescEn, string DescTr, string DescUr,
    string LocAr, string LocEn, string LocTr, string LocUr,
    string StreamUrl,
    RadioKind Kind,
    string? ArtworkFile = null,
    bool IsTopical = false)
{
    public string Name(string lang) => lang switch { "ar" => NameAr, "ur" => NameUr, "tr" => NameTr, _ => NameEn };
    public string Description(string lang) => lang switch { "ar" => DescAr, "ur" => DescUr, "tr" => DescTr, _ => DescEn };
    public string Location(string lang) => lang switch { "ar" => LocAr, "ur" => LocUr, "tr" => LocTr, _ => LocEn };
    public bool HasPlace => LocEn != "Live";
}

